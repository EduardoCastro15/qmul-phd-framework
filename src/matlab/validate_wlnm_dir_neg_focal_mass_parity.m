function report = validate_wlnm_dir_neg_focal_mass_parity(mat_file, report_file)
%VALIDATE_WLNM_DIR_NEG_FOCAL_MASS_PARITY Compare historical WLNM with mode A.
% This smoke writes only temporary auxiliary files and never touches a
% historical result directory. An optional JSON report can be requested.

    if nargin < 1 || isempty(mat_file)
        mat_file = fullfile('data','foodwebs_mat','SF1M2_tax_mass.mat');
    end
    if nargin < 2
        report_file = '';
    end

    matlab_root = fileparts(mfilename('fullpath'));
    addpath(genpath(fullfile(matlab_root, 'wlnm_version_runners')));
    addpath(genpath(fullfile(matlab_root, 'software')));
    addpath(genpath(fullfile(matlab_root, 'metrics')));
    ensure_nauty_mex();

    input = load(mat_file, 'net', 'taxonomy', 'mass', 'role');
    [~, dataname] = fileparts(mat_file);
    split_seed = 12345;
    model_seed = 24680;
    K = 10;
    ratio_train = 0.60;

    rng(split_seed, 'twister');
    [train, test] = DivideNet_dir_neg(input.net, ratio_train, false, false);
    [train_i, train_j] = find(train);
    [test_i, test_j] = find(test);
    positive_hash = make_focal_mass_link_split_hash(size(train,1), ...
        [train_i train_j], [test_i test_j]);

    rng(model_seed, 'twister');
    [train_pos, train_neg, test_pos, test_neg] = sample_neg_dir_neg( ...
        train, test, input.role, 2, 1, false, true, input.mass, false, 1.0, ...
        'uniform_remaining_nonlinks', 'uniform_without_replacement', ...
        'role_only', [], []);
    expected_negative_hash = make_focal_mass_link_split_hash( ...
        size(train,1), train_neg, test_neg);

    [historical_train, historical_train_labels] = graph2vector_dir_neg( ...
        train_pos, train_neg, train, K, false, dataname, false);
    [focal_train, focal_train_labels] = graph2vector_dir_neg_focal_mass( ...
        train_pos, train_neg, train, K, false, dataname, false);
    [historical_test, historical_test_labels] = graph2vector_dir_neg( ...
        test_pos, test_neg, train, K, false, dataname, false);
    [focal_test, focal_test_labels] = graph2vector_dir_neg_focal_mass( ...
        test_pos, test_neg, train, K, false, dataname, false);
    assert(isequal(historical_train, focal_train));
    assert(isequal(historical_test, focal_test));
    assert(isequal(historical_train_labels, focal_train_labels));
    assert(isequal(historical_test_labels, focal_test_labels));

    temporary_root = tempname;
    mkdir(temporary_root);
    cleanup = onCleanup(@() rmdir(temporary_root, 's')); %#ok<NASGU>
    historical_dir = fullfile(temporary_root, 'historical');
    focal_dir = fullfile(temporary_root, 'focal');
    mkdir(historical_dir); mkdir(focal_dir);

    common = { ...
        'save_confusion', true, ...
        'evaluate_on_all_unseen', false, ...
        'threshold_mode', 'fixed', ...
        'fixed_threshold', 0.50, ...
        'encode_parallel', false, ...
        'compute_ecological_metrics', false, ...
        'trophic_protocol', 'legacy_v1', ...
        'trophic_high_precision', 'off', ...
        'negative_eligibility_mode', 'role_only', ...
        'negative_positive_ratio', 2, ...
        'negative_sampling_strategy', 'uniform_without_replacement', ...
        'negative_topup_policy', 'uniform_remaining_nonlinks', ...
        'negative_mass_eligibility_enabled', false};

    rng(model_seed, 'twister');
    [old_roc, old_pr, old_threshold, old_precision, old_recall, old_f1] = ...
        WLNM_dir_neg(dataname, train, test, K, input.taxonomy, input.mass, ...
        input.role, 'random', ratio_train, common{:}, ...
        'artifact_dir', historical_dir, 'artifact_tag', 'historical', ...
        'model_version', 'WLNM_dir_neg');

    rng(model_seed, 'twister');
    [new_roc, new_pr, new_threshold, new_precision, new_recall, new_f1, new_aux] = ...
        WLNM_dir_neg_focal_mass(dataname, train, test, K, input.taxonomy, ...
        input.mass, input.role, 'random', ratio_train, common{:}, ...
        'artifact_dir', focal_dir, 'artifact_tag', 'focal', ...
        'model_version', 'WLNM_dir_neg_focal_mass', ...
        'focal_mass_feature_mode', 'structure_only');

    old_scores = read_single_score_file(historical_dir);
    new_scores = read_single_score_file(focal_dir);
    assert(isequal(old_scores.Label, new_scores.Label));
    score_max_abs_difference = max(abs(old_scores.Score - new_scores.Score));
    metric_old = [old_roc old_pr old_threshold old_precision old_recall old_f1];
    metric_new = [new_roc new_pr new_threshold new_precision new_recall new_f1];
    metric_max_abs_difference = max(abs(metric_old - metric_new));
    tolerance = 1e-10;
    assert(score_max_abs_difference <= tolerance);
    assert(metric_max_abs_difference <= tolerance);
    assert(strcmp(new_aux.NegativeSplitHash, expected_negative_hash));
    assert(new_aux.FocalMassFeatureDim == 0 && new_aux.ModelInputDim == 90);

    report = struct( ...
        'ValidationStatus','VALIDATION_OK', ...
        'Foodweb',dataname, ...
        'SplitSeed',split_seed, ...
        'ModelSeed',model_seed, ...
        'PositiveSplitHash',positive_hash, ...
        'NegativeSplitHash',expected_negative_hash, ...
        'StructuralTrainVectorsIdentical',true, ...
        'StructuralTestVectorsIdentical',true, ...
        'LabelsIdentical',true, ...
        'ScoreMaxAbsDifference',score_max_abs_difference, ...
        'MetricMaxAbsDifference',metric_max_abs_difference, ...
        'Tolerance',tolerance, ...
        'HistoricalInputDim',size(historical_train,2), ...
        'ModeAInputDim',new_aux.ModelInputDim, ...
        'TargetMaskingProtocol',new_aux.TargetMaskingProtocol);

    if ~isempty(report_file)
        report_parent = fileparts(report_file);
        if ~isempty(report_parent) && ~isfolder(report_parent)
            mkdir(report_parent);
        end
        fid = fopen(report_file, 'w');
        assert(fid ~= -1, 'Cannot open parity report: %s', report_file);
        close_report = onCleanup(@() fclose(fid)); %#ok<NASGU>
        fprintf(fid, '%s\n', jsonencode(report, 'PrettyPrint', true));
    end
    fprintf('VALIDATION_OK focal-mass mode A parity | max score diff %.3g | max metric diff %.3g\n', ...
        score_max_abs_difference, metric_max_abs_difference);
end

function scores = read_single_score_file(directory)
    files = dir(fullfile(directory, '*_scores_labels.csv'));
    assert(numel(files) == 1, 'Expected one score file in %s, found %d.', ...
        directory, numel(files));
    scores = readtable(fullfile(files(1).folder, files(1).name));
end
