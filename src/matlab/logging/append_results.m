function append_results(log_file, results, use_backbone)
    %APPEND_RESULTS Append an array of result structs to CSV.
    % First column (ExpID/Iteration) is sequential across the whole file.

    % ---- Find last used ID in this log_file (if any) ----
    if isfile(log_file)
        fid_read = fopen(log_file, 'r');
        assert(fid_read ~= -1, 'Cannot open %s for reading.', log_file);

        lastID = 0;

        % Skip header line
        headerLine = fgetl(fid_read); %#ok<NASGU>

        % Walk through lines and keep last numeric ID from first column
        line = fgetl(fid_read);
        while ischar(line)
            if ~isempty(line)
                commaPos = find(line == ',', 1, 'first');
                if ~isempty(commaPos)
                    token = line(1:commaPos-1);
                else
                    token = line;
                end
                val = str2double(strtrim(token));
                if ~isnan(val)
                    lastID = val;
                end
            end
            line = fgetl(fid_read);
        end

        fclose(fid_read);
    else
        lastID = 0;
    end

    % ---- Append new rows with sequential IDs ----
    for i = 1:numel(results)
        expID = lastID + i;

        fid = fopen(log_file, 'a');
        assert(fid ~= -1, 'Cannot open %s for appending.', log_file);

        if use_backbone
            fprintf(fid, ...
                ['%d,%.4f,%s,%d,%.0f,%.0f,%.2f,%.4f,%.4f,%.4f,' ...
                 '%d,%d,%d,%d,%d,%d,%d,%d,%d\n'], ...
                expID, ...
                results(i).AUC, ...
                results(i).TimeElapsed, ...
                results(i).K, ...
                results(i).TrainRatio * 100, ...
                results(i).BackboneRatio * 100, ...
                results(i).Threshold, ...
                results(i).Precision, ...
                results(i).Recall, ...
                results(i).F1Score, ...
                results(i).TotalLinks, ...
                results(i).TrainLinks, ...
                results(i).TestLinks, ...
                results(i).BackboneTotal, ...
                results(i).NonBackboneTotal, ...
                results(i).BackboneTrainLinks, ...
                results(i).NonBackboneTrainLinks, ...
                results(i).BackboneTestLinks, ...
                results(i).NonBackboneTestLinks);
        else
            fprintf(fid, ...
                ['%d,%.4f,%s,%d,%.0f,%.2f,%.4f,%.4f,%.4f,' ...
                 '%d,%d,%d,%d,%d,%d,%d,%d,%d\n'], ...
                expID, ...
                results(i).AUC, ...
                results(i).TimeElapsed, ...
                results(i).K, ...
                results(i).TrainRatio * 100, ...
                results(i).Threshold, ...
                results(i).Precision, ...
                results(i).Recall, ...
                results(i).F1Score, ...
                results(i).TotalLinks, ...
                results(i).TrainLinks, ...
                results(i).TestLinks, ...
                results(i).BackboneTotal, ...
                results(i).NonBackboneTotal, ...
                results(i).BackboneTrainLinks, ...
                results(i).NonBackboneTrainLinks, ...
                results(i).BackboneTestLinks, ...
                results(i).NonBackboneTestLinks);
        end

        fclose(fid);
    end
end
