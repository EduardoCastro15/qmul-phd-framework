function out = copy_auxiliary_fields(out, aux)
    node_fields = { ...
        'NodeEcologyFeatureDim','ModelInputDim','MassPreprocessingProtocol', ...
        'ValidMassNodeCount','MissingMassNodeCount','TrainingNodeCount', ...
        'NegativeSplitHash','NegativeRoleSource','NodeAlignmentProtocol', ...
        'TargetMaskingProtocol'};
    for index = 1:numel(node_fields)
        field = node_fields{index};
        if isfield(aux, field)
            out.(field) = aux.(field);
        end
    end

    if isfield(aux, 'test_metrics') && ~isempty(aux.test_metrics)
        test_metrics = aux.test_metrics;
        mappings = { ...
            'TP','TestTP'; 'FP','TestFP'; 'FN','TestFN'; 'TN','TestTN'; ...
            'TPR','TestTPR'; 'TNR','TestTNR'; 'FPR','TestFPR'; 'FNR','TestFNR'; ...
            'Precision','TestPrecision'; 'Recall','TestRecall'; ...
            'F1Score','TestF1Score'; 'Accuracy','TestAccuracy'; ...
            'ExpectedAccuracy','TestExpectedAccuracy'; 'Kappa','TestKappa'; ...
            'MCC','TestMCC'; 'TSS','TestTSS'};
        for index = 1:size(mappings, 1)
            source = mappings{index, 1};
            target = mappings{index, 2};
            if isfield(test_metrics, source)
                out.(target) = test_metrics.(source);
            end
        end
    end

    if isfield(aux, 'negative_sampling') && ~isempty(aux.negative_sampling)
        negative = aux.negative_sampling;
        fields = { ...
            'RolePoolSize','MassPoolSize','EligiblePoolSize','FullNegativePoolSize', ...
            'RequestedNegativeCount','SelectedNegativeCount','EligibleNegativeCount', ...
            'EligibleShortfall','FullPoolShortfall','RandomTopupCount', ...
            'TopupProportion','TrainNegativeCount','TestNegativeCount', ...
            'CandidatePairCount','ObservedZeroPoolSize', ...
            'TrainNegativeBothEndpointsVisible','TrainNegativeOneEndpointVisible', ...
            'TrainNegativeNeitherEndpointVisible','TestNegativeBothEndpointsVisible', ...
            'TestNegativeOneEndpointVisible','TestNegativeNeitherEndpointVisible', ...
            'TestPositiveBothEndpointsVisible','TestPositiveOneEndpointVisible', ...
            'TestPositiveNeitherEndpointVisible','TrainTestNegativeOverlapCount', ...
            'PositiveTrainTestOverlapCount'};
        for index = 1:numel(fields)
            field = fields{index};
            if isfield(negative, field)
                out.(field) = negative.(field);
            end
        end
    end
end

function [experiment_id, fold_id] = unit_coordinates(unit_index, cv_k)
    experiment_id = floor((unit_index - 1) / cv_k) + 1;
    fold_id = mod(unit_index - 1, cv_k) + 1;
end

function stats = make_split_stats(net, train, test)
    stats = struct( ...
        'TotalLinks', nnz(net), ...
        'TrainLinks', nnz(train), ...
        'TestLinks', nnz(test));
end

function hash_text = make_positive_split_hash(train, test)
    [train_i, train_j] = find(train);
    [test_i, test_j] = find(test);
    payload = sprintf('n=%d|train=', size(train, 1));
    payload = [payload, sprintf('%d:%d;', [train_i, train_j]')];
    payload = [payload, '|test=', ...
        sprintf('%d:%d;', [test_i, test_j]')];
    digest = java.security.MessageDigest.getInstance('SHA-256');
    digest.update(uint8(payload));
    bytes = typecast(digest.digest(), 'uint8');
    hash_text = lower(reshape(dec2hex(bytes, 2)', 1, []));
end

function seed = make_repeated_cv_seed(base_seed, dataname, cv_k, ...
        experiment_id, fold_id, purpose)
    payload = sprintf('%s|%s|cvk=%d|repeat=%d|fold=%d|base=%d', ...
        char(string(purpose)), char(string(dataname)), cv_k, ...
        experiment_id, fold_id, round(double(base_seed)));
    digest = java.security.MessageDigest.getInstance('SHA-256');
    digest.update(uint8(payload));
    bytes = typecast(digest.digest(), 'uint8');
    hex = lower(reshape(dec2hex(bytes, 2)', 1, []));
    seed = mod(hex2dec(hex(1:8)), 2147483646) + 1;
end

function value = get_data_field(data, field, default_value)
    if isfield(data, field) && ~isempty(data.(field))
        value = data.(field);
    else
        value = default_value;
    end
end

function value = get_config_bool(config, field, default_value)
    if isfield(config, field) && ~isempty(config.(field))
        value = logical(config.(field));
    else
        value = logical(default_value);
    end
end

function value = get_config_number(config, field, default_value)
    if isfield(config, field) && ~isempty(config.(field))
        value = double(config.(field));
    else
        value = default_value;
    end
end

function value = get_config_text(config, field, default_value)
    if isfield(config, field) && ~isempty(config.(field))
        value = char(string(config.(field)));
    else
        value = char(string(default_value));
    end
end
