function results = run_wlnm_dir_neg_node_ecology_kfold(data, K, ~, config)
%RUN_WLNM_DIR_NEG_NODE_ECOLOGY_KFOLD Repeated directed k-fold node ecology.
% Each ExperimentID receives an independently seeded balanced fold
% partition. The node-ecology model is fitted separately for every fold.

    addpath(fileparts(mfilename('fullpath')), '-begin');

    version = get_config_text(config, 'version', ...
        'WLNM_dir_neg_node_ecology_kfold');
    cv_k = get_config_number(config, 'cvK', 5);
    num_experiments = get_config_number(config, 'numExperiments', 20);
    if ~isscalar(num_experiments) || ~isfinite(num_experiments) || ...
            num_experiments < 1 || floor(num_experiments) ~= num_experiments
        error('WLNMDirNegNodeEcologyKfold:NumExperiments', ...
            'numExperiments must be one positive integer.');
    end

    validate_dir_neg_node_ecology_kfold_scope( ...
        version, K, get_config_bool(config, 'cvEnabled', false), cv_k, ...
        get_config_text(config, 'thresholdMode', 'fixed'), ...
        get_config_number(config, 'fixedThreshold', 0.50), ...
        get_config_bool(config, 'thresholdSweepEnabled', false), ...
        get_config_text(config, 'negativeEligibilityMode', ''), ...
        get_config_number(config, 'negativePositiveRatio', NaN), ...
        get_config_text(config, 'negativeSamplingStrategy', ''), ...
        get_config_text(config, 'negativeTopupPolicy', ''), ...
        get_config_bool(config, 'negativeMassEligibilityEnabled', false), ...
        get_config_bool(config, 'computeEcologicalMetrics', true));

    dataname = char(string(data.dataname));
    net = spones(sparse(data.net));
    n = size(net, 1);
    net = net - spdiags(diag(net), 0, n, n);
    net = spones(net);
    taxonomy = data.taxonomy;
    mass = data.mass;
    node_selection = config.nodeSelection;
    ratio_train = (cv_k - 1) / cv_k;
    cv_seed = get_config_number(config, 'cvSeed', 12345);
    base_seed = get_config_number(config, 'baseSeed', 12345);

    if isfield(data, 'backbone_mask') && ~isempty(data.backbone_mask)
        error('WLNMDirNegNodeEcologyKfold:BackboneNotSupported', ...
            'The frozen repeated-CV campaign does not support a backbone mask.');
    end

    observed_negative_mask = get_data_field(data, 'observed_negative_mask', []);
    candidate_mask = get_data_field(data, 'candidate_mask', []);
    artifact_dir = get_config_text(config, 'artifactDir', ...
        'data/result/confusion_matrix_csv/');
    if ~exist(artifact_dir, 'dir')
        mkdir(artifact_dir);
    end
    partition_cells = cell(num_experiments, 1);
    partition_seeds = zeros(num_experiments, 1);
    partition_hashes = cell(num_experiments, 1);
    for experiment_id = 1:num_experiments
        partition_seeds(experiment_id) = make_repeated_cv_seed( ...
            cv_seed, dataname, cv_k, experiment_id, 0, 'partition');
        partition_cells{experiment_id} = ...
            build_repeated_directed_edge_folds( ...
                net, cv_k, partition_seeds(experiment_id));
        partition_hashes{experiment_id} = ...
            make_repeated_cv_partition_hash(partition_cells{experiment_id});
    end

    if numel(unique(partition_seeds)) ~= num_experiments || ...
            numel(unique(partition_hashes)) ~= num_experiments
        error('WLNMDirNegNodeEcologyKfold:RepeatedPartitionCollision', ...
            'Each ExperimentID must have a distinct split seed and partition hash.');
    end

    unit_count = num_experiments * cv_k;
    unit_results = cell(unit_count, 1);
    use_parallel = get_config_bool(config, 'useParallel', true);
    if use_parallel
        parfor unit_index = 1:unit_count
            [experiment_id, fold_id] = unit_coordinates(unit_index, cv_k);
            unit_results{unit_index} = run_one_fold( ...
                experiment_id, fold_id, partition_cells{experiment_id}, ...
                partition_seeds(experiment_id), ...
                partition_hashes{experiment_id}, base_seed, dataname, ...
                net, K, ratio_train, config, taxonomy, mass, ...
                node_selection, observed_negative_mask, candidate_mask, ...
                unit_index == 1);
        end
    else
        for unit_index = 1:unit_count
            [experiment_id, fold_id] = unit_coordinates(unit_index, cv_k);
            unit_results{unit_index} = run_one_fold( ...
                experiment_id, fold_id, partition_cells{experiment_id}, ...
                partition_seeds(experiment_id), ...
                partition_hashes{experiment_id}, base_seed, dataname, ...
                net, K, ratio_train, config, taxonomy, mass, ...
                node_selection, observed_negative_mask, candidate_mask, ...
                unit_index == 1);
        end
    end

    results = repmat(unit_results{1}, unit_count, 1);
    for unit_index = 1:unit_count
        results(unit_index) = unit_results{unit_index};
    end

    observed_keys = [[results.ExperimentID]', [results.FoldID]'];
    expected_keys = zeros(unit_count, 2);
    cursor = 0;
    for experiment_id = 1:num_experiments
        for fold_id = 1:cv_k
            cursor = cursor + 1;
            expected_keys(cursor, :) = [experiment_id, fold_id];
        end
    end
    if ~isequal(observed_keys, expected_keys)
        error('WLNMDirNegNodeEcologyKfold:ResultOrdering', ...
            'Repeated-CV results are incomplete or out of deterministic order.');
    end
end

function out = run_one_fold(experiment_id, fold_id, folds, split_seed, ...
        partition_hash, base_seed, dataname, net, K, ratio_train, config, ...
        taxonomy, mass, node_selection, observed_negative_mask, ...
        candidate_mask, first_unit)

    test_indices = find(folds.fold_id == fold_id);
    test = sparse( ...
        folds.i(test_indices), folds.j(test_indices), 1, folds.n, folds.n);
    train = spones(net - test);
    test = spones(test);

    if nnz(train & test) ~= 0 || nnz(train + test) ~= nnz(net)
        error('WLNMDirNegNodeEcologyKfold:InvalidFold', ...
            'Train/test overlap or incomplete coverage in repeat %d fold %d.', ...
            experiment_id, fold_id);
    end
    split_stats = make_split_stats(net, train, test);
    positive_split_hash = make_positive_split_hash(train, test);
    model_seed = make_repeated_cv_seed( ...
        base_seed, dataname, folds.k, experiment_id, fold_id, 'model');
    rng(model_seed, 'twister');

    save_confusion = get_config_bool(config, 'cvSaveConfusion', false) && first_unit;
    version = get_config_text(config, 'version', ...
        'WLNM_dir_neg_node_ecology_kfold');
    cv_tag = sprintf('repeated_cv_k%d_repeat%02d_fold%02d', ...
        folds.k, experiment_id, fold_id);
    artifact_tag = sprintf('%s_seed%d', lower(version), model_seed);
    encode_parallel = get_config_bool( ...
        config, 'useGraphEncodingParallel', false) && ...
        ~get_config_bool(config, 'useParallel', true);

    t0 = tic;
    [roc_auc, pr_auc, thresholds, precisions, recalls, f1_scores, aux_rows] = ...
        WLNM_dir_neg_node_ecology( ...
            dataname, train, test, K, taxonomy, mass, node_selection, ratio_train, ...
            'cv_tag', cv_tag, ...
            'save_confusion', save_confusion, ...
            'backbone_mask', [], ...
            'export_backbone', false, ...
            'evaluate_on_all_unseen', false, ...
            'artifact_tag', artifact_tag, ...
            'artifact_dir', get_config_text(config, 'artifactDir', ...
                'data/result/confusion_matrix_csv/'), ...
            'threshold_mode', 'fixed', ...
            'fixed_threshold', 0.50, ...
            'threshold_sweep_enabled', false, ...
            'encode_parallel', encode_parallel, ...
            'compute_ecological_metrics', false, ...
            'model_version', 'WLNM_dir_neg_node_ecology', ...
            'trophic_protocol', get_config_text(config, ...
                'trophicLevelProtocol', 'validated_v2'), ...
            'trophic_high_precision', get_config_text(config, ...
                'trophicHighPrecision', 'auto'), ...
            'trophic_snapshot_dir', '', ...
            'trophic_metadata', struct( ...
                'ExperimentID', experiment_id, ...
                'Seed', model_seed, ...
                'Version', version, ...
                'CvK', folds.k, ...
                'FoldID', fold_id), ...
            'negative_eligibility_mode', 'role_only', ...
            'negative_positive_ratio', 2, ...
            'negative_sampling_strategy', 'uniform_without_replacement', ...
            'negative_topup_policy', 'uniform_remaining_nonlinks', ...
            'observed_negative_mask', observed_negative_mask, ...
            'candidate_mask', candidate_mask, ...
            'negative_mass_eligibility_enabled', false, ...
            'negative_mass_eligibility_threshold', 1.0);
    elapsed_seconds = toc(t0);

    if numel(thresholds) ~= 1 || ~isfinite(thresholds(1)) || ...
            abs(double(thresholds(1)) - 0.50) > 1e-12
        error('WLNMDirNegNodeEcologyKfold:ThresholdRows', ...
            'Every fold must return exactly one finite threshold-0.50 row.');
    end

    out = make_result_template( ...
        K, ratio_train, folds.k, fold_id, experiment_id, model_seed, ...
        split_seed, partition_hash, positive_split_hash, split_stats, config);
    out.ROC_AUC = roc_auc;
    out.PR_AUC = pr_auc;
    out.TimeElapsed = datestr(seconds(elapsed_seconds), 'HH:MM:SS');
    out.Threshold = thresholds(1);
    out.Precision = precisions(1);
    out.Recall = recalls(1);
    out.F1Score = f1_scores(1);
    out = copy_auxiliary_fields(out, aux_rows(1));

    fprintf(['[NodeEcologyRepeatedCV] %s | K=%d | repeat %d/%d | ' ...
        'fold %d/%d | ROC-AUC=%.4f | PR-AUC(AP)=%.4f\n'], ...
        dataname, folds.k, experiment_id, ...
        get_config_number(config, 'numExperiments', 20), fold_id, folds.k, ...
        roc_auc, pr_auc);
end

