function validate_dir_neg_node_ecology_kfold_scope(version, K, cv_enabled, cv_k, ...
        threshold_mode, fixed_threshold, threshold_sweep_enabled, ...
        eligibility_mode, negative_ratio, sampling_strategy, topup_policy, ...
        mass_eligibility_enabled, compute_ecological_metrics)
%VALIDATE_DIR_NEG_NODE_ECOLOGY_KFOLD_SCOPE Freeze the repeated-CV protocol.

    if ~strcmpi(strtrim(char(string(version))), ...
            'WLNM_dir_neg_node_ecology_kfold')
        error('WLNMDirNegNodeEcologyKfold:Version', ...
            'This route requires Version=WLNM_dir_neg_node_ecology_kfold.');
    end
    if ~isscalar(K) || ~isfinite(K) || K ~= 10
        error('WLNMDirNegNodeEcologyKfold:SubgraphSize', ...
            'The node-ecology k-fold protocol requires K=10.');
    end
    if ~logical(cv_enabled)
        error('WLNMDirNegNodeEcologyKfold:CrossValidation', ...
            'The node-ecology k-fold route requires cvEnabled=true.');
    end
    if ~isscalar(cv_k) || ~isfinite(cv_k) || ...
            ~ismember(double(cv_k), [3 5 10])
        error('WLNMDirNegNodeEcologyKfold:CvK', ...
            'CvK must be one of 3, 5, or 10.');
    end
    if ~strcmpi(strtrim(char(string(threshold_mode))), 'fixed') || ...
            ~isscalar(fixed_threshold) || ~isfinite(fixed_threshold) || ...
            abs(double(fixed_threshold) - 0.50) > 1e-12 || ...
            logical(threshold_sweep_enabled)
        error('WLNMDirNegNodeEcologyKfold:ThresholdProtocol', ...
            'The protocol requires fixed threshold 0.50 and no threshold sweep.');
    end
    if ~strcmpi(strtrim(char(string(eligibility_mode))), 'role_only') || ...
            ~isscalar(negative_ratio) || ~isfinite(negative_ratio) || ...
            abs(double(negative_ratio) - 2) > 1e-12 || ...
            ~strcmpi(strtrim(char(string(sampling_strategy))), ...
                'uniform_without_replacement') || ...
            ~strcmpi(strtrim(char(string(topup_policy))), ...
                'uniform_remaining_nonlinks') || ...
            logical(mass_eligibility_enabled)
        error('WLNMDirNegNodeEcologyKfold:NegativeProtocol', ...
            ['The protocol requires role_only, ratio=2, ' ...
             'uniform_without_replacement, uniform_remaining_nonlinks, ' ...
             'and mass eligibility disabled.']);
    end
    if logical(compute_ecological_metrics)
        error('WLNMDirNegNodeEcologyKfold:EcologicalMetrics', ...
            'This campaign is predictive-only; ecological metrics must be disabled.');
    end
end
