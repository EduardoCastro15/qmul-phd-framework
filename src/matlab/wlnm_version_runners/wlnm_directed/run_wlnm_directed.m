function results = run_wlnm_directed(data, K, ratioTrain, config)
    %RUN_WLNM_DIRECTED Runner for WLNM with directed sampling.

    % Preallocate result objects with extended CSV schema
    results = repmat(make_result_template_directed(K, ratioTrain, empty_split_stats(), config, 0, 0), ...
        config.numExperiments, 1);

    % Broadcast-friendly locals
    dataname      = data.dataname;
    net           = data.net;
    taxonomy      = data.taxonomy;
    mass          = data.mass;
    role          = data.role;
    nodeSelection = config.nodeSelection;
    baseSeed      = get_config_number_directed(config, 'baseSeed', 12345);
    resampleSplits = get_config_bool_directed(config, 'resampleSplitsEachExperiment', true);
    saveAux = get_config_bool_directed(config, 'exportAuxiliaryCSVs', false);
    artifactDir = get_config_text_directed(config, 'artifactDir', 'data/result/confusion_matrix_csv/');
    thresholdMode = get_config_text_directed(config, 'thresholdMode', 'fixed');
    fixedThreshold = get_config_number_directed(config, 'fixedThreshold', 0.5);
    evaluateOnAllUnseen = get_config_bool_directed(config, 'evaluate_on_all_unseen', false);
    encodeParallel = get_config_bool_directed(config, 'useGraphEncodingParallel', false) && ~logical(config.useParallel);
    computeEcologicalMetrics = get_config_bool_directed(config, 'computeEcologicalMetrics', true);

    sharedTrain = [];
    sharedTest = [];
    sharedStats = [];
    if ~resampleSplits
        splitSeed = make_experiment_seed_directed(baseSeed, dataname, K, ratioTrain, 0);
        rng(splitSeed, 'twister');
        [sharedTrain, sharedTest, ~, ~] = DivideNet_directed(net, ratioTrain);
        sharedStats = make_split_stats_directed(sharedTrain, sharedTest);
    end

    % Execute experiments
    if config.useParallel
        startIdx = 1;
        if saveAux
            results(1) = one_experiment_directed( ...
                1, baseSeed, dataname, net, K, ratioTrain, taxonomy, mass, role, ...
                nodeSelection, config, sharedTrain, sharedTest, sharedStats, true, ...
                artifactDir, thresholdMode, fixedThreshold, evaluateOnAllUnseen, ...
                encodeParallel, computeEcologicalMetrics);
            startIdx = 2;
        end

        if startIdx <= config.numExperiments
            parfor i = startIdx:config.numExperiments
                results(i) = one_experiment_directed( ...
                    i, baseSeed, dataname, net, K, ratioTrain, taxonomy, mass, role, ...
                    nodeSelection, config, sharedTrain, sharedTest, sharedStats, false, ...
                    artifactDir, thresholdMode, fixedThreshold, evaluateOnAllUnseen, ...
                    encodeParallel, computeEcologicalMetrics);
            end
        end
    else
        for i = 1:config.numExperiments
            results(i) = one_experiment_directed( ...
                i, baseSeed, dataname, net, K, ratioTrain, taxonomy, mass, role, ...
                nodeSelection, config, sharedTrain, sharedTest, sharedStats, saveAux && i == 1, ...
                artifactDir, thresholdMode, fixedThreshold, evaluateOnAllUnseen, ...
                encodeParallel, computeEcologicalMetrics);
        end
    end
end

function r = one_experiment_directed(i, baseSeed, dataname, net, K, ratioTrain, taxonomy, mass, role, ...
        nodeSelection, config, sharedTrain, sharedTest, sharedStats, saveConfusion, artifactDir, ...
        thresholdMode, fixedThreshold, evaluateOnAllUnseen, encodeParallel, computeEcologicalMetrics)

    seed = make_experiment_seed_directed(baseSeed, dataname, K, ratioTrain, i);
    rng(seed, 'twister');

    if isempty(sharedTrain)
        [train, test, ~, ~] = DivideNet_directed(net, ratioTrain);
        splitStats = make_split_stats_directed(train, test);
    else
        train = sharedTrain;
        test = sharedTest;
        splitStats = sharedStats;
    end

    t0 = tic;
    disp(['Experiment ', num2str(i), ' (node selection: ', char(nodeSelection), ') - Running WLNM_directed...']);

    artifactTag = sprintf('%s_exp%03d_seed%d', lower(get_config_text_directed(config, 'version', 'WLNM_directed')), i, seed);

    [roc_auc, pr_auc, best_threshold, best_precision, best_recall, best_f1_score, aux] = ...
        WLNM_directed(dataname, train, test, K, taxonomy, mass, role, nodeSelection, ratioTrain, ...
            'save_confusion', saveConfusion, ...
            'artifact_tag', artifactTag, ...
            'artifact_dir', artifactDir, ...
            'threshold_mode', thresholdMode, ...
            'fixed_threshold', fixedThreshold, ...
            'ith_experiment', i, ...
            'evaluate_on_all_unseen', evaluateOnAllUnseen, ...
            'encode_parallel', encodeParallel, ...
            'compute_ecological_metrics', computeEcologicalMetrics);

    r = make_result_template_directed(K, ratioTrain, splitStats, config, i, seed);
    r = populate_result_row_directed( ...
        r, roc_auc, pr_auc, best_threshold, best_precision, best_recall, ...
        best_f1_score, toc(t0), aux);
end

