function validate_dir_neg_node_ecology_scope(version, K, cv_enabled, ...
        threshold_mode, fixed_threshold, threshold_sweep_enabled, ...
        eligibility_mode, negative_ratio, sampling_strategy, topup_policy, ...
        mass_eligibility_enabled)
%VALIDATE_DIR_NEG_NODE_ECOLOGY_SCOPE Freeze the node-ecology protocol.

    if ~strcmpi(strtrim(char(string(version))), 'WLNM_dir_neg_node_ecology')
        error('WLNMDirNegNodeEcology:Version', ...
            'This protocol requires Version=WLNM_dir_neg_node_ecology.');
    end
    if ~isscalar(K) || ~isfinite(K) || K ~= 10
        error('WLNMDirNegNodeEcology:SubgraphSize', ...
            'The node-ecology protocol requires K=10.');
    end
    if logical(cv_enabled)
        error('WLNMDirNegNodeEcology:CrossValidation', ...
            'The first node-ecology protocol does not support k-fold routing.');
    end
    if ~strcmpi(strtrim(char(string(threshold_mode))), 'fixed') || ...
            ~isscalar(fixed_threshold) || ~isfinite(fixed_threshold) || ...
            abs(double(fixed_threshold)-0.5) > 1e-12 || ...
            logical(threshold_sweep_enabled)
        error('WLNMDirNegNodeEcology:ThresholdProtocol', ...
            'The protocol requires fixed threshold 0.50 and no threshold sweep.');
    end
    if ~strcmpi(strtrim(char(string(eligibility_mode))), 'role_only') || ...
            ~isscalar(negative_ratio) || ~isfinite(negative_ratio) || ...
            abs(double(negative_ratio)-2) > 1e-12 || ...
            ~strcmpi(strtrim(char(string(sampling_strategy))), ...
                'uniform_without_replacement') || ...
            ~strcmpi(strtrim(char(string(topup_policy))), ...
                'uniform_remaining_nonlinks') || ...
            logical(mass_eligibility_enabled)
        error('WLNMDirNegNodeEcology:NegativeProtocol', ...
            ['The protocol requires role_only, ratio=2, ' ...
             'uniform_without_replacement, uniform_remaining_nonlinks, ' ...
             'and mass eligibility disabled.']);
    end
end
