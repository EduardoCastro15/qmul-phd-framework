% ============================================================
% Empty split stats template
% ============================================================
function st = empty_split_stats()
    st = struct( ...
        'TotalLinks',0, ...
        'TrainLinks',0, ...
        'TestLinks',0, ...
        'BackboneTotal',0, ...
        'NonBackboneTotal',0, ...
        'BackboneTrainLinks',0, ...
        'NonBackboneTrainLinks',0, ...
        'BackboneTestLinks',0, ...
        'NonBackboneTestLinks',0 ...
    );
end

% ============================================================
% Fill predictive + ecological metrics into result row
% ============================================================
function out = populate_result_row(out, roc_auc, pr_auc, thr, prec, rec, f1, elapsed_seconds, aux)

    out.ROC_AUC     = roc_auc;
    out.PR_AUC      = pr_auc;
    out.TimeElapsed = datestr(seconds(elapsed_seconds), 'HH:MM:SS');
    out.Threshold   = thr;
    out.Precision   = prec;
    out.Recall      = rec;
    out.F1Score     = f1;

    flat = flatten_aux_metrics(aux);
    fn = fieldnames(flat);
    for k = 1:numel(fn)
        out.(fn{k}) = flat.(fn{k});
    end
end

% ============================================================
% Flatten aux struct from WLNM_dir_neg into scalar fields
% ============================================================
function flat = flatten_aux_metrics(aux)

    flat = struct( ...
        'EmpiricalNumSpecies',NaN, ...
        'EmpiricalLinks',NaN, ...
        'EmpiricalConnectance',NaN, ...
        'EmpiricalMeanTrophicLevel',NaN, ...
        'EmpiricalMeanDegree',NaN, ...
        'EmpiricalMeanGenerality',NaN, ...
        'EmpiricalMeanVulnerability',NaN, ...
        'EmpiricalPropBasal',NaN, ...
        'EmpiricalPropIntermediate',NaN, ...
        'EmpiricalPropTop',NaN, ...
        'PseudoNumSpecies',NaN, ...
        'PseudoLinks',NaN, ...
        'PseudoConnectance',NaN, ...
        'PseudoMeanTrophicLevel',NaN, ...
        'PseudoMeanDegree',NaN, ...
        'PseudoMeanGenerality',NaN, ...
        'PseudoMeanVulnerability',NaN, ...
        'PseudoPropBasal',NaN, ...
        'PseudoPropIntermediate',NaN, ...
        'PseudoPropTop',NaN, ...
        'DeltaLinks',NaN, ...
        'DeltaConnectance',NaN, ...
        'DeltaMeanTrophicLevel',NaN, ...
        'DeltaMeanDegree',NaN, ...
        'DeltaMeanGenerality',NaN, ...
        'DeltaMeanVulnerability',NaN, ...
        'DeltaPropBasal',NaN, ...
        'DeltaPropIntermediate',NaN, ...
        'DeltaPropTop',NaN, ...
        'PseudoTP',NaN, ...
        'PseudoFP',NaN, ...
        'PseudoFN',NaN, ...
        'PseudoTN',NaN, ...
        'PseudoTPR',NaN, ...
        'PseudoTNR',NaN, ...
        'PseudoFPR',NaN, ...
        'PseudoFNR',NaN, ...
        'PseudoPrecision',NaN, ...
        'PseudoRecall',NaN, ...
        'PseudoF1Score',NaN, ...
        'PseudoTSS',NaN, ...
        'PseudoJaccardLinks',NaN, ...
        'NumPredictedNovelLinks',NaN, ...
        'NumTrueNovelLinks',NaN, ...
        'EvaluateOnAllUnseen',NaN ...
    );

    if nargin == 0 || isempty(aux)
        return;
    end

    % ---- empirical metrics ----
    if isfield(aux, 'empirical_metrics') && ~isempty(aux.empirical_metrics)
        m = aux.empirical_metrics;
        flat.EmpiricalNumSpecies        = safe_field(m, 'NumSpecies');
        flat.EmpiricalLinks             = safe_field(m, 'NumLinks');
        flat.EmpiricalConnectance       = safe_field(m, 'Connectance');
        flat.EmpiricalMeanTrophicLevel  = safe_field(m, 'MeanTrophicLevel');
        flat.EmpiricalMeanDegree        = safe_field(m, 'MeanDegree');
        flat.EmpiricalMeanGenerality    = safe_field(m, 'MeanGenerality');
        flat.EmpiricalMeanVulnerability = safe_field(m, 'MeanVulnerability');
        flat.EmpiricalPropBasal         = safe_field(m, 'PropBasal');
        flat.EmpiricalPropIntermediate  = safe_field(m, 'PropIntermediate');
        flat.EmpiricalPropTop           = safe_field(m, 'PropTop');
    end

    % ---- pseudo metrics ----
    if isfield(aux, 'pseudo_metrics') && ~isempty(aux.pseudo_metrics)
        m = aux.pseudo_metrics;
        flat.PseudoNumSpecies        = safe_field(m, 'NumSpecies');
        flat.PseudoLinks             = safe_field(m, 'NumLinks');
        flat.PseudoConnectance       = safe_field(m, 'Connectance');
        flat.PseudoMeanTrophicLevel  = safe_field(m, 'MeanTrophicLevel');
        flat.PseudoMeanDegree        = safe_field(m, 'MeanDegree');
        flat.PseudoMeanGenerality    = safe_field(m, 'MeanGenerality');
        flat.PseudoMeanVulnerability = safe_field(m, 'MeanVulnerability');
        flat.PseudoPropBasal         = safe_field(m, 'PropBasal');
        flat.PseudoPropIntermediate  = safe_field(m, 'PropIntermediate');
        flat.PseudoPropTop           = safe_field(m, 'PropTop');
    end

    % ---- deltas ----
    flat.DeltaLinks             = flat.PseudoLinks            - flat.EmpiricalLinks;
    flat.DeltaConnectance       = flat.PseudoConnectance      - flat.EmpiricalConnectance;
    flat.DeltaMeanTrophicLevel  = flat.PseudoMeanTrophicLevel - flat.EmpiricalMeanTrophicLevel;
    flat.DeltaMeanDegree        = flat.PseudoMeanDegree       - flat.EmpiricalMeanDegree;
    flat.DeltaMeanGenerality    = flat.PseudoMeanGenerality   - flat.EmpiricalMeanGenerality;
    flat.DeltaMeanVulnerability = flat.PseudoMeanVulnerability- flat.EmpiricalMeanVulnerability;
    flat.DeltaPropBasal         = flat.PseudoPropBasal        - flat.EmpiricalPropBasal;
    flat.DeltaPropIntermediate  = flat.PseudoPropIntermediate - flat.EmpiricalPropIntermediate;
    flat.DeltaPropTop           = flat.PseudoPropTop          - flat.EmpiricalPropTop;

    % ---- comparison metrics ----
    if isfield(aux, 'comparison_metrics') && ~isempty(aux.comparison_metrics)
        c = aux.comparison_metrics;
        flat.PseudoTP           = safe_field(c, 'TP');
        flat.PseudoFP           = safe_field(c, 'FP');
        flat.PseudoFN           = safe_field(c, 'FN');
        flat.PseudoTN           = safe_field(c, 'TN');
        flat.PseudoTPR          = safe_field(c, 'TPR');
        flat.PseudoTNR          = safe_field(c, 'TNR');
        flat.PseudoFPR          = safe_field(c, 'FPR');
        flat.PseudoFNR          = safe_field(c, 'FNR');
        flat.PseudoPrecision    = safe_field(c, 'Precision');
        flat.PseudoRecall       = safe_field(c, 'Recall');
        flat.PseudoF1Score      = safe_field(c, 'F1Score');
        flat.PseudoTSS          = safe_field(c, 'TSS');
        flat.PseudoJaccardLinks = safe_field(c, 'JaccardLinks');
    end

    % ---- bookkeeping ----
    if isfield(aux, 'NumPredictedNovelLinks')
        flat.NumPredictedNovelLinks = aux.NumPredictedNovelLinks;
    end
    if isfield(aux, 'NumTrueNovelLinks')
        flat.NumTrueNovelLinks = aux.NumTrueNovelLinks;
    end
    if isfield(aux, 'EvaluateOnAllUnseen')
        flat.EvaluateOnAllUnseen = double(aux.EvaluateOnAllUnseen);
    end
end

% ============================================================
% Safe struct field access
% ============================================================
function val = safe_field(s, f)
    if isstruct(s) && isfield(s, f) && ~isempty(s.(f))
        val = s.(f);
    else
        val = NaN;
    end
end
