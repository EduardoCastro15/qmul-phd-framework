function results = run_wlnm_dir_neg(data, K, ratioTrain, config)
%RUN_WLNM_DIR_NEG Runner for WLNM with directed + negative sampling.

    % ---- Minimal required config fields (controlled from Main) ----
    required_fields = { ...
        'useParallel', ...
        'use_backbone', ...
        'inverse_backbone', ...
        'sweepBackboneTrain', ...
        'BackboneRatio', ...
        'backboneRatioRange', ...
        'numExperiments', ...
        'nodeSelection', ...
        'cvSaveConfusion', ...
        'evaluate_on_all_unseen', ...
        'exportBackboneCSV' ...
    };

    for kf = 1:numel(required_fields)
        f = required_fields{kf};
        if ~isfield(config, f)
            error('[run_wlnm_dir_neg] Missing required config field: %s. Define it in Main.m.', f);
        end
    end

    % ---- Backbone usage comes ONLY from Main ----
    has_mask = isfield(data, 'backbone_mask') && ~isempty(data.backbone_mask);

    use_backbone = logical(config.use_backbone) && has_mask;

    if config.use_backbone && ~has_mask
        warning(['[run_wlnm_dir_neg] config.use_backbone=true but data.backbone_mask is empty. ' ...
                 'Falling back to standard split. Backbone must be computed in Main.m.']);
    end

    if config.inverse_backbone && ~use_backbone
        warning(['[run_wlnm_dir_neg] inverse_backbone=true but no backbone_mask was provided. ' ...
                 'Inverse backbone mode will be ignored for this dataset.']);
    end

    % ---- Backbone ratio list ----
    if use_backbone
        if config.sweepBackboneTrain
            rb_list = config.backboneRatioRange;
        else
            rb_list = config.BackboneRatio;
        end
        rb_list = rb_list(:)';   % row vector
    else
        rb_list = 0;
    end

    % ---- Preallocate results ----
    R = numel(rb_list) * config.numExperiments;
    results = repmat(make_result_template(K, ratioTrain, 0, empty_split_stats()), R, 1);

    % ---- Locals ----
    dataname      = data.dataname;
    net           = data.net;
    taxonomy      = data.taxonomy;
    mass          = data.mass;
    role          = data.role;
    nodeSelection = config.nodeSelection;

    backbone_mask = [];
    if has_mask
        backbone_mask = data.backbone_mask;
    end

    % ---- Confusion / export control ----
    save_confusion_flag = logical(config.cvSaveConfusion);
    export_backbone_flag = logical(config.exportBackboneCSV);

    row = 0;

    for rb = rb_list
        % ------------------------------------------------------------
        % Backbone mask: ONLY use precomputed one from Main
        % ------------------------------------------------------------
        if use_backbone
            bb_mask = backbone_mask;
        else
            bb_mask = [];
        end

        % ------------------------------------------------------------
        % Obtain train/test split
        % ------------------------------------------------------------
        if use_backbone
            fprintf('[SweepBackbone] ratioTrain=%.2f | BackboneRatio=%.2f | inverse_backbone=%d\n', ...
                ratioTrain, rb, config.inverse_backbone);

            args = { ...
                'use_backbone',      true, ...
                'ratioBackbone',     rb, ...
                'inverse_backbone',  config.inverse_backbone, ...
                'backbone_mask',     bb_mask ...
            };

            [train, test, split_stats] = DivideNet_dir_neg(net, ratioTrain, false, false, args{:});
        else
            [train, test, split_stats] = DivideNet_dir_neg(net, ratioTrain, false, false);
        end

        % ------------------------------------------------------------
        % WLNM experiments
        % ------------------------------------------------------------
        if config.useParallel
            res_block = repmat(make_result_template(K, ratioTrain, rb, split_stats), config.numExperiments, 1);

            start_idx = 1;
            if save_confusion_flag
                t0 = tic;
                [roc_auc, pr_auc, thr, prec, rec, f1, aux] = WLNM_dir_neg( ...
                    dataname, train, test, K, taxonomy, mass, role, nodeSelection, ratioTrain, ...
                    'save_confusion', true, ...
                    'backbone_mask', bb_mask, ...
                    'export_backbone', (use_backbone && export_backbone_flag), ...
                    'evaluate_on_all_unseen', config.evaluate_on_all_unseen);

                res_block(1) = populate_result_row( ...
                    res_block(1), roc_auc, pr_auc, thr, prec, rec, f1, toc(t0), aux);

                start_idx = 2;
            end

            if start_idx <= config.numExperiments
                parfor i = start_idx:config.numExperiments
                    t0 = tic;

                    [roc_auc, pr_auc, thr, prec, rec, f1, aux] = WLNM_dir_neg( ...
                        dataname, train, test, K, taxonomy, mass, role, nodeSelection, ratioTrain, ...
                        'save_confusion', false, ...
                        'backbone_mask', bb_mask, ...
                        'export_backbone', false, ...
                        'evaluate_on_all_unseen', config.evaluate_on_all_unseen);

                    local_res = make_result_template(K, ratioTrain, rb, split_stats);
                    local_res = populate_result_row( ...
                        local_res, roc_auc, pr_auc, thr, prec, rec, f1, toc(t0), aux);

                    res_block(i) = local_res;
                end
            end

            for i = 1:config.numExperiments
                row = row + 1;
                results(row) = res_block(i);
            end

        else
            for i = 1:config.numExperiments
                do_export = save_confusion_flag && (i == 1);

                t0 = tic;
                [roc_auc, pr_auc, thr, prec, rec, f1, aux] = WLNM_dir_neg( ...
                    dataname, train, test, K, taxonomy, mass, role, nodeSelection, ratioTrain, ...
                    'save_confusion', do_export, ...
                    'backbone_mask', bb_mask, ...
                    'export_backbone', (do_export && use_backbone && export_backbone_flag), ...
                    'evaluate_on_all_unseen', config.evaluate_on_all_unseen);

                row = row + 1;

                results(row) = make_result_template(K, ratioTrain, rb, split_stats);
                results(row) = populate_result_row( ...
                    results(row), roc_auc, pr_auc, thr, prec, rec, f1, toc(t0), aux);
            end
        end
    end
end

