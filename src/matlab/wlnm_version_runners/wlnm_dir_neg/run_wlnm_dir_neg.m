    if isfield(config, field) && ~isempty(config.(field))
        value = config.(field);
    else
        value = default_value;
    end
end

function value = get_config_text(config, field, default_value)
    if isfield(config, field) && ~isempty(config.(field))
        value = char(string(config.(field)));
    else
        value = char(string(default_value));
    end
end
