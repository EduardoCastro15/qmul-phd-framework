% ============================================================
% Safe struct field access
% ============================================================
function s = add_extended_metric_defaults(s, prefix)
    suffixes = extended_metric_suffixes();
    for i = 1:numel(suffixes)
        s.([prefix suffixes{i}]) = NaN;
    end
end

function s = copy_extended_metrics(s, metrics, prefix)
    suffixes = extended_metric_suffixes();
    for i = 1:numel(suffixes)
        suffix = suffixes{i};
        s.([prefix suffix]) = safe_field(metrics, suffix);
    end
end

function s = compute_extended_metric_deltas(s)
    suffixes = extended_metric_suffixes();
    for i = 1:numel(suffixes)
        suffix = suffixes{i};
        s.(['Delta' suffix]) = s.(['Pseudo' suffix]) - s.(['Empirical' suffix]);
    end
end

function suffixes = extended_metric_suffixes()
    suffixes = { ...
        'DegreeStd', ...
        'DegreeCV', ...
        'DegreeGini', ...
        'GeneralityStd', ...
        'GeneralityCV', ...
        'GeneralityGini', ...
        'VulnerabilityStd', ...
        'VulnerabilityCV', ...
        'VulnerabilityGini', ...
        'TrophicLevelStd', ...
        'TrophicLevelCV', ...
        'TrophicLevelRange', ...
        'MeanLocalClustering', ...
        'Transitivity', ...
        'NumTriangles', ...
        'TriangleDensity', ...
        'MeanDietOverlap' ...
    };
end

function val = safe_field(s, f)
    if isstruct(s) && isfield(s, f) && ~isempty(s.(f))
        val = s.(f);
    else
        val = NaN;
    end
end

function seed = make_experiment_seed(base_seed, dataname, K, ratioTrain, rb, expID)
    name_hash = sum(double(char(string(dataname))));
    raw = double(base_seed) ...
        + 1000003 * name_hash ...
        + 1009 * double(K) ...
        + 9173 * round(1000 * double(ratioTrain)) ...
        + 131 * round(1000 * double(rb)) ...
        + double(expID);
    seed = mod(round(raw), 2147483646) + 1;
end

function tag = make_artifact_tag(version, expID, seed, rb, inverse_backbone)
    if inverse_backbone
        rb_tag = sprintf('nonbb%03d', round(100 * rb));
    else
        rb_tag = sprintf('bb%03d', round(100 * rb));
    end
    tag = sprintf('%s_%s_exp%03d_seed%d', lower(char(string(version))), rb_tag, expID, seed);
end

