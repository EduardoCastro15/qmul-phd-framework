function mode = normalize_focal_mass_feature_mode(value)
%NORMALIZE_FOCAL_MASS_FEATURE_MODE Validate the focal-mass ablation mode.

    mode = lower(strtrim(char(string(value))));
    mode = strrep(mode, '-', '_');
    mode = regexprep(mode, '\s+', '_');

    allowed = { ...
        'structure_only', ...
        'endpoint_masses', ...
        'mass_ratio', ...
        'endpoint_masses_ratio' ...
    };
    if ~any(strcmp(mode, allowed))
        error('WLNMDirNegFocalMass:InvalidFeatureMode', ...
            'FocalMassFeatureMode must be one of: %s. Got "%s".', ...
            strjoin(allowed, ', '), char(string(value)));
    end
end
