function validate_dir_neg_focal_mass_scope(version, protocol, high_precision, ...
        eligibility_mode, negative_ratio, sampling_strategy, topup_policy, ...
        mass_eligibility_enabled)
%VALIDATE_DIR_NEG_FOCAL_MASS_SCOPE Freeze the first focal-mass protocol.

    if ~strcmpi(strtrim(char(string(version))), 'WLNM_dir_neg_focal_mass')
        error('WLNMDirNegFocalMass:Version', ...
            'This runner requires Version=WLNM_dir_neg_focal_mass.');
    end
    if ~any(strcmp(protocol, {'legacy_v1','validated_v2'})) || ...
            ~any(strcmp(high_precision, {'auto','off','required'}))
        error('WLNMDirNegFocalMass:TrophicConfiguration', ...
            'Unknown trophic protocol or precision mode.');
    end
    if strcmp(high_precision, 'required') && ...
            ~(exist('sym','file') == 2 && license('test','Symbolic_Toolbox'))
        error('WLNMDirNegFocalMass:TrophicPrecisionUnavailable', ...
            'Symbolic Math Toolbox is required.');
    end
    if ~strcmp(eligibility_mode, 'role_only') || ...
            abs(double(negative_ratio) - 2) > 1e-12 || ...
            ~strcmp(sampling_strategy, 'uniform_without_replacement') || ...
            ~strcmp(topup_policy, 'uniform_remaining_nonlinks') || ...
            logical(mass_eligibility_enabled)
        error('WLNMDirNegFocalMass:Protocol', ...
            ['The frozen focal-mass protocol requires role_only, ratio=2, ' ...
             'uniform_without_replacement, uniform_remaining_nonlinks, and ' ...
             'mass eligibility disabled.']);
    end
end
